// Product image pipeline. Run: npm run images
//  - Reads untouched originals from /assets-src/<product>/<name>.(webp|jpg|png)  (never served)
//  - Writes AVIF + WebP at 480/768/1080/1600 (never upscaled) to /public/images/products/<product>/
//  - Writes a tiny blurred placeholder per image into config/photos.generated.ts (width/height/widths/blur)
//  - Writes the 1200x630 Open Graph image (pouch in the right third, #23201C on the left, M+ logo)
import sharp from "sharp";
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const WIDTHS = [480, 768, 1080, 1600];
const SRC = "assets-src";
const OUT = "public/images/products";
const BG = "#23201C";

const meta = {};
for (const product of await readdir(SRC, { withFileTypes: true })) {
  if (!product.isDirectory()) continue;
  const outDir = path.join(OUT, product.name);
  await mkdir(outDir, { recursive: true });
  for (const file of await readdir(path.join(SRC, product.name))) {
    const name = path.parse(file).name;
    const input = path.join(SRC, product.name, file);
    const { width: W, height: H } = await sharp(input).metadata();
    const widths = WIDTHS.filter((w) => w <= W); // never upscale
    if (!widths.length) widths.push(W);
    for (const w of widths) {
      const base = path.join(outDir, `${name}-${w}`);
      const img = () => sharp(input).resize({ width: w, withoutEnlargement: true });
      await img().avif({ quality: 62, effort: 4 }).toFile(base + ".avif"); // AVIF q62 ≈ WebP q80 visually
      await img().webp({ quality: 80 }).toFile(base + ".webp");
    }
    const blurBuf = await sharp(input).resize({ width: 24 }).blur(1).webp({ quality: 50 }).toBuffer();
    meta[`/images/products/${product.name}/${name}`] = {
      width: W,
      height: H,
      widths,
      blur: `data:image/webp;base64,${blurBuf.toString("base64")}`,
    };
    console.log("✓", product.name, name, widths.join("/"));
  }
}

await writeFile(
  "config/photos.generated.ts",
  `// GENERATED by scripts/make-images.mjs. Do not edit.\nexport type PhotoMeta = { width: number; height: number; widths: number[]; blur: string };\nexport const photoMeta: Record<string, PhotoMeta> = ${JSON.stringify(meta, null, 2)};\n`,
);

// ---- Open Graph / Twitter image from the pouch hero ----
async function og(file) {
  const hero = "assets-src/red-burn/red-burn-pouch-hero.webp";
  // Crop the empty sides only (pouch spans ~20%-81% of the width), keep full height, so no packaging is cut.
  const pouch = await sharp(hero)
    .extract({ left: 245, top: 0, width: 1127, height: 2000 })
    .resize({ height: 630 })
    .png()
    .toBuffer();
  const pw = (await sharp(pouch).metadata()).width;
  const left = 1200 - pw;
  const fade = Buffer.from(
    `<svg width="1200" height="630" xmlns="http://www.w3.org/2000/svg"><defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="${BG}" stop-opacity="1"/><stop offset="1" stop-color="${BG}" stop-opacity="0"/></linearGradient></defs><rect x="${left}" y="0" width="110" height="630" fill="url(#g)"/></svg>`,
  );
  const logo = await sharp("public/brand/miel-m-plus.png").resize({ width: 300 }).toBuffer();
  const lh = (await sharp(logo).metadata()).height;
  await sharp({ create: { width: 1200, height: 630, channels: 4, background: BG } })
    .composite([
      { input: pouch, left, top: 0 },
      { input: fade, left: 0, top: 0 },
      { input: logo, left: 110, top: Math.round((630 - lh) / 2) },
    ])
    .png()
    .toFile(file);
  console.log("✓ og", file);
}
await og("app/opengraph-image.png");
await og("app/twitter-image.png");
await mkdir("public/images/og", { recursive: true });
await og("public/images/og/red-burn.png");
